def one():
    negative = 0 # инициализируем переменную для хранения отрицательных значений функции
    """ чтобы в цикле перебирать значения с шагом нужно использовать range, но в Питоне range работает только с integer """
    """ поэтому просто домножим на 10 чтобы шаг 0.5 стал целым числом, внутри цикла поделим на 10 """
    """ Т.к. крайнаа граница промежутка не попадает в цикл for то ставим границу 55 """
    for x in range(-50, 55, 5):
        x = x / 10
        y = x ** 2 - 4 * x + 3 # формула квадратного уравнения
        print(f"X = {x}, Y = {y}")
        if y < 0: # если значение функции отрицатедное то увеличиваем счетчик
            negative += 1 # negative = negative + 1
    print(f"Всего значений функции меньше нуля: {negative} раз(а)")


