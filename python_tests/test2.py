def two():
    positive_sum = 0  # сумма положительных чисел
    positive_count = 0 # количсетво положительных чисел
    even_sum = 0 # сумма четных чисел
    count = 0 # общее количество чисел
    mean = 0 # среднее арифмитическое положительных чисел
    while (a := int(input("Введите чилсло (ноль выход): "))) != 0:
        count += 1 # увеличиваем счетчик чисел
        if a % 2 == 0: # если число делитеся на 2 без остатка то оно четное
            even_sum += a # увеличиваем сумму четных чисел
        if a > 0: # если число положительное, то увеличиваем сумму и счетчик положительных чисел
            positive_count += 1
            positive_sum += a
    print(f"Количество введеных чисел: {count}")
    print(f"Сумма всех четных чисел: {even_sum}")
    if positive_count > 0: # если количество положительных чисел больше 0, то считаем среднеее арифмитическое для положительных чисел
        mean = positive_sum / positive_count 
        print(f"Срднее арифмитическое положительных чисел {mean}")
    else:
        print("Положительных чисел не было")


""" третье задание """
def three():
    n = int(input("Введите натуральное число: "))
    result = [] # список простых делителей
    for i in range(2, n): # запускаем цикл от 2 до n (на 1 и на сомого себя делятся все числа )
        if n % i == 0: # если число из промежутка делит число без остатка, то это делитель
            simple = True # предпологаем что делитель простой
            for j in range(2, i): # осталось проверить что делитель простой (простое число делится только на 1 и на само себя, есди оно делится еще на что то, то оно не простое)
                if i % j == 0: # делитель делится еще на какое то число без остатка, то сбрасываем перемнную "простости")) в False
                    simple = False
            if simple: # если делитель все таки простой, то добавляем его в список делителей
                result.append(i)
    if result == []: # если делителей не было найдено, то само введенное число простое
        print(f"Число {n} простое")
    else: # иначе выводим список дклитклей
        print(f"Простые делители числа {n}: {result}")
                

